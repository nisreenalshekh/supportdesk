// small helper so the seed below stays readable
function ticket(t: Partial<Ticket> & Pick<Ticket, "id" | "subject" | "category" | "priority" | "status" | "requesterId" | "createdAt" | "slaDueAt">): Ticket {
  return {
    description: t.subject,
    assigneeId: null,
    assignedAt: null,
    resolvedAt: null,
    messages: [],
    attachments: [],
    ...t,
  };
}

